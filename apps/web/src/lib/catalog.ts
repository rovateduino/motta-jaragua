const categoryBySlug = new Map(catalogCategories.map((category) => [category.slug, category]));

export function getCategoryBySlug(slug: string): CatalogCategory | undefined {
  return categoryBySlug.get(slug);
}

export function getCategoryName(slug: string): string {
  return getCategoryBySlug(slug)?.name ?? "Departamento";
}

/** Aplica a promoção vigente sobre o preço base do produto. */
export function priceProduct(
  product: CatalogProduct,
  now: Date = new Date(),
): PricedCatalogProduct {
  const promotion = getActivePromotion(product.sku, now);

  if (!promotion) {
    return { ...product, priceCents: product.basePriceCents };
  }

  return {
    ...product,
    priceCents: resolveEffectivePriceCents({
      basePriceCents: product.basePriceCents,
      promotion,
      now,
    }),
    originalPriceCents: product.basePriceCents,
    promotion: {
      id: promotion.id,
      conditions: promotion.conditions,
      endsAt: promotion.endsAt.toISOString(),
      ...(promotion.maxQuantityPerOrderMilli === undefined
        ? {}
        : { maxQuantityPerOrderMilli: promotion.maxQuantityPerOrderMilli }),
    },
  };
}

export function getPricedProducts(now: Date = new Date()): PricedCatalogProduct[] {
  return catalogProducts.map((product) => priceProduct(product, now));
}

export function getPricedProductById(
  id: string,
  now: Date = new Date(),
): PricedCatalogProduct | undefined {
  const product = rawProductById.get(id);
  return product ? priceProduct(product, now) : undefined;
}

export function getPricedProductBySlug(
  slug: string,
  now: Date = new Date(),
): PricedCatalogProduct | undefined {
  const product = rawProductBySlug.get(slug);
  return product ? priceProduct(product, now) : undefined;
}

export function getRelatedProducts(
  product: PricedCatalogProduct,
  limit = 4,
  now: Date = new Date(),
): PricedCatalogProduct[] {
  return selectRelatedProducts(getPricedProducts(now), product, limit);
}

export function getCatalogOffers(now: Date = new Date()): PricedCatalogProduct[] {
  return getPricedProducts(now).filter(hasPromotion);
}
